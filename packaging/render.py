#!/usr/bin/env python3
"""Render the package-manager manifests of one bcli release from its signed SHA256SUMS.

    python3 packaging/render.py --sums SHA256SUMS --out DIR

The version comes from the VERSION line's file next to SHA256SUMS (or --version). Writes
    DIR/homebrew-tap/Formula/bcli.rb                         -> servas-ai/homebrew-tap
    DIR/scoop-bucket/bucket/bcli.json                        -> servas-ai/scoop-bucket
    DIR/winget/manifests/s/servas/bcli/X.Y.Z/servas.bcli*.yaml -> microsoft/winget-pkgs
Check the signature of SHA256SUMS first (install.sh does it, or docs/installation.md).
"""
import argparse
import json
import re
from pathlib import Path

REPO = "servas-ai/bcli-public"
BREW_DESC = "Real, headed cloud browsers for agents and tests over CDP (servas.ai)"
DESC = "CLI for servas.ai Browser as a Service: real, headed cloud browsers for agents and tests over CDP"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--sums", required=True)
    ap.add_argument("--version")
    ap.add_argument("--out", required=True)
    ap.add_argument("--date", default=__import__("datetime").date.today().isoformat(), help="release date YYYY-MM-DD")
    a = ap.parse_args()
    sums = {}
    for line in Path(a.sums).read_text().splitlines():
        m = re.fullmatch(r"([0-9a-f]{64})  ([A-Za-z0-9._-]+)", line)
        if not m:
            raise SystemExit(f"bad SHA256SUMS line: {line!r}")
        sums[m.group(2)] = m.group(1)
    version = a.version or (Path(a.sums).parent / "VERSION").read_text().strip()
    if not re.fullmatch(r"[0-9]+\.[0-9]+\.[0-9]+", version):
        raise SystemExit("package managers get final versions only (X.Y.Z)")
    base = f"https://github.com/{REPO}/releases/download/v{version}"
    out = Path(a.out)

    def h(name):
        if name not in sums:
            raise SystemExit(f"{name} missing in SHA256SUMS")
        return sums[name]

    formula = f'''# Generated by servas-ai/bcli-public packaging/render.py from the signed SHA256SUMS of v{version}.
class Bcli < Formula
  desc "{BREW_DESC}"
  homepage "https://github.com/{REPO}"
  version "{version}"
  license :cannot_represent

  on_macos do
    on_arm do
      url "{base}/bcli-darwin-arm64"
      sha256 "{h("bcli-darwin-arm64")}"
    end
    on_intel do
      url "{base}/bcli-darwin-amd64"
      sha256 "{h("bcli-darwin-amd64")}"
    end
  end

  on_linux do
    on_arm do
      url "{base}/bcli-linux-arm64"
      sha256 "{h("bcli-linux-arm64")}"
    end
    on_intel do
      url "{base}/bcli-linux-amd64"
      sha256 "{h("bcli-linux-amd64")}"
    end
  end

  livecheck do
    url :stable
    strategy :github_latest
  end

  def install
    bin.install Dir["bcli-*"].first => "bcli"
  end

  def caveats
    <<~EOS
      Upgrade with `brew upgrade bcli`. Sign in:
        bcli env add cloud --kind cloud --endpoint https://api.baas.servas.ai && bcli env use cloud
        bcli login
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{{bin}}/bcli version")
  end
end
'''
    p = out / "homebrew-tap/Formula/bcli.rb"
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(formula)

    scoop = {
        "version": version,
        "description": DESC,
        "homepage": f"https://github.com/{REPO}",
        "license": {"identifier": "Proprietary", "url": f"https://github.com/{REPO}/blob/main/LICENSE"},
        "architecture": {
            "64bit": {"url": f"{base}/bcli-windows-amd64.exe#/bcli.exe", "hash": h("bcli-windows-amd64.exe")}
        },
        "bin": "bcli.exe",
        "notes": [
            "Sign in: bcli env add cloud --kind cloud --endpoint https://api.baas.servas.ai; bcli env use cloud; bcli login",
            "Use a normal (non-elevated) terminal. Upgrade with: scoop update bcli",
        ],
        "checkver": {"github": f"https://github.com/{REPO}"},
        "autoupdate": {
            "architecture": {
                "64bit": {
                    "url": f"https://github.com/{REPO}/releases/download/v$version/bcli-windows-amd64.exe#/bcli.exe",
                    "hash": {"url": "$baseurl/SHA256SUMS", "regex": "$sha256\\s+bcli-windows-amd64\\.exe"},
                }
            }
        },
    }
    p = out / "scoop-bucket/bucket/bcli.json"
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(json.dumps(scoop, indent=4) + "\n")

    wdir = out / f"winget/manifests/s/servas/bcli/{version}"
    wdir.mkdir(parents=True, exist_ok=True)
    schema = "1.10.0"
    head = "# yaml-language-server: $schema=https://aka.ms/winget-manifest.{kind}.%s.schema.json\n\n" % schema
    (wdir / "servas.bcli.yaml").write_text(head.format(kind="version") + f"""PackageIdentifier: servas.bcli
PackageVersion: {version}
DefaultLocale: en-US
ManifestType: version
ManifestVersion: {schema}
""")
    (wdir / "servas.bcli.installer.yaml").write_text(head.format(kind="installer") + f"""PackageIdentifier: servas.bcli
PackageVersion: {version}
InstallerType: portable
Commands:
- bcli
ReleaseDate: {a.date}
Installers:
- Architecture: x64
  InstallerUrl: {base}/bcli-windows-amd64.exe
  InstallerSha256: {h("bcli-windows-amd64.exe").upper()}
ManifestType: installer
ManifestVersion: {schema}
""")
    (wdir / "servas.bcli.locale.en-US.yaml").write_text(head.format(kind="defaultLocale") + f"""PackageIdentifier: servas.bcli
PackageVersion: {version}
PackageLocale: en-US
Publisher: servas.ai
PublisherUrl: https://servas.ai
PublisherSupportUrl: https://github.com/{REPO}/issues
PackageName: bcli
PackageUrl: https://github.com/{REPO}
License: Proprietary
LicenseUrl: https://github.com/{REPO}/blob/main/LICENSE
ShortDescription: {DESC}.
Description: bcli starts real, headed Chromium browsers in the servas.ai cloud (or locally) and hands you a standard Chrome DevTools Protocol endpoint for Playwright, Puppeteer or AI agents. Needs a servas.ai account.
Moniker: bcli
Tags:
- browser
- cdp
- playwright
- puppeteer
- automation
- agents
- cli
ReleaseNotesUrl: https://github.com/{REPO}/releases/tag/v{version}
ManifestType: defaultLocale
ManifestVersion: {schema}
""")
    print(f"rendered v{version} into {out}")


if __name__ == "__main__":
    main()
